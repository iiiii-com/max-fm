/** 按牛熊轮次分组 */
export function groupEventsByCycle() {
  const map = new Map<string, BullBearEvent[]>();
  for (const e of BULL_BEAR_EVENTS) {
    if (!map.has(e.cycle)) map.set(e.cycle, []);
    map.get(e.cycle)!.push(e);
  }
  // 按日期排序
  for (const arr of map.values()) arr.sort((a, b) => a.date.localeCompare(b.date));
  return map;
}

