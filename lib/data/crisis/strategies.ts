/**
 * 危机阶段策略 —— 每场危机每个阶段的场景化应对。
 *
 * 为什么不放在组件里：
 * 原实现把策略写成 CrisisEngine.tsx 内部的 STAGE_TIPS 常量，只覆盖 2 场共 11 个阶段；
 * 其余 18 场 / 57 个阶段（83.8%）走 fallbackTip()，返回同一段
 * "熊市铁律 / 牛市铁律 / 震荡铁律"通用纪律 + grade:"C" + winRate:"通用纪律"。
 * 也就是说 20 场危机里有 19 场的玩家在看同一段模板 —— 这正是"占位感"的来源。
 *
 * 现在策略下沉到数据层，与 crisis.stages 数组**按下标一一对应**，
 * 由 scripts/verify-crisis-tips.ts 断言覆盖率，避免再次退化。
 *
 * 字段口径：
 *   strategy  该阶段具体该做什么（可执行，不是口号）
 *   grade     A 高确定性 / B 中等 / C 需谨慎
 *   winRate   历史区间的胜率估计，用于给"做对了能赚多少"一个量级感
 *   drawdown  走错方向的最大回撤参考
 *
 * ⚠ winRate 是**区间估计而非统计结果**。样本极少（单次危机），
 * 真实历史频率无法用几个样本准确估计，这里给的是从业者经验区间，
 * 用途是让用户对风险收益比有量级直觉，不是精确胜率。
 */

