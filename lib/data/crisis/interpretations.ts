/**
 * 把补丁层合入危机数据：narrative 取「文件内已有 > 补丁表」，
 * 节点的 policy / marketNote 同样只在缺失时补，不覆盖文件里的原值。
 * 纯函数、不改原对象，供 CrisisEngine 与回归脚本共用。
 */
export function withInterpretation(crisis: Crisis): Crisis {
  const patch = CRISIS_NARRATIVES[crisis.id];
  const notes = NODE_NOTES[crisis.id] ?? {};

  if (!patch && !Object.keys(notes).length) return crisis;

  const nodes: CrisisNode[] = (crisis.nodes ?? []).map((n) => {
    const note = notes[n.date];
    if (!note) return n;
    return {
      ...n,
      policy: n.policy ?? note.policy,
      marketNote: n.marketNote ?? note.marketNote,
    };
  });

  return {
    ...crisis,
    nodes,
    narrative: crisis.narrative ?? patch,
  };
}
