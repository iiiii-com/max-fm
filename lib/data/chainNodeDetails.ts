/**
 * 产业链环节的结构化维度 —— 34 条链 × 173 个环节。
 *
 * 为什么需要这一层（chainNodeInsights.ts 之上）：
 * 那一份给每个环节一段讲解，能读但不能比、不能查、字段维度单一。
 * 城市解读有 8 个维度（产业/特点/就业/收入/支出/优势/短板/生活质量），
 * 而环节此前只有 name + level + companies + 一段话 ——
 * 这正是"产业地图内容单薄"的结构性原因，不是文字量不够。
 *
 * 这里把环节拆成可对照的维度：
 *  - products 做什么：具体产品或服务，回答"这一环具体产什么"
 *  - value     利润归属：这一环赚什么钱、对上下游议价能力如何
 *  - barriers  进入壁垒：为什么别人进不来（或进得来）
 *  - metrics   跟踪指标：可公开查证的指标**名称**，不含数值
 *  - risks     环节风险：这个环节最可能怎么出问题
 *
 * ── 数据纪律 ────────────────────────────────────────────────────────
 * metrics 只写指标名称，绝不写数值 —— 数值由 chain_metrics 表在满足
 * 「单位 + 时点 + 来源 + 口径」四件套校验后才展示，避免两处数字打架。
 * value 写机制不写毛利率百分比（理由同 chainEconomics.ts）。
 *
 * 键名必须与 scripts/seed.ts 里的节点名**逐字一致**（含空格）。
 * 差一个空格就会静默退回模板 —— 这个坑踩过一次，
 * scripts/verify-chain-content.ts 会双向核对。
 */

