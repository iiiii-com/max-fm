/**
 * 产业链的全球格局与国产化进度 —— 40 条链逐条撰写。
 *
 * 为什么单独成文件：
 * chainInsights.ts 回答「钱怎么流、风险在哪」，chainEconomics.ts 回答
 * 「利润落在哪一段」。这两个维度回答的是另一类问题：
 *  - globalPosition：这条链在全球分工里处于什么位置、国产化到了哪一步
 *  - cyclePosition：现在处在周期的哪个阶段、还有多少空间
 * 它们是读者判断「值不值得看这条链」的前置信息，因此单独组织。
 *
 * ── 数据纪律 ────────────────────────────────────────────────────────
 * 国产化率是本文件最容易出问题的地方：具体百分比在不同报告里口径差异极大
 * （有的按产值、有的按产能、有的按装机量），且很多细分环节没有公开统计。
 * 因此这里**不写具体百分比**，只写定性的位置判断与关键制约，
 * 并说明判断依据与不确定性。凡涉及具体数字的，应去查该细分领域的
 * 权威报告并注意其口径 —— 站内不替读者选择一个来源。
 *
 * 同样，cyclePosition 只写位置判断与判断依据，不写"还有 X% 空间"这类
 * 看似精确实则无源的推算。
 */

export interface ChainGlobalPosition {
  /** 全球分工位置：中国在这一环是主导、跟随还是追赶 */
  globalRole: string;
  /** 国产化到了哪一步（定性判断，不写百分比） */
  localization: string;
  /** 卡在哪里：阻碍国产化的具体因素 */
  localizationBlockers: string[];
  /** 竞争的真正对手是谁（而非泛泛的"海外厂商"） */
  keyCompetitors: string[];
}

export interface ChainCyclePosition {
  /** 周期位置判断 */
  stage: string;
  /** 判断依据：凭什么这么判断 */
  basis: string[];
  /** 向上还是向下：边际变化方向与关键变量 */
  direction: string;
  /** 什么会推翻这个判断 */
  invalidators: string[];
}

/** slug → 全球格局 */
export type ChainMarketPosition = Record<string, ChainGlobalPosition>;
/** slug → 周期位置 */
export type ChainCycle = Record<string, ChainCyclePosition>;

