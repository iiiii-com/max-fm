function series(type: string, i: number): number {
  const t = i / 12;
  const season = Math.sin(t * Math.PI * 2) * 0.6;
  const noise = (rng() - 0.5) * 1.4;
  switch (type) {
    case "cpi": return round1(1.6 + t * -0.02 + season * 0.5 + noise * 0.4);
    case "ppi": return round1(-1.5 + t * 0.12 + season * 0.4 + noise);
    case "pmi": return round1(50.1 + Math.sin(t * Math.PI * 0.6) * 0.9 + noise * 0.5);
    case "m2": return round1(8.4 + t * 0.15 + noise * 0.4);
    case "tsf": return round2(2.3 + Math.abs(noise) * 1.2 + season * 0.6);
    case "export": return round1(3.5 + t * 0.1 + season * 1.5 + noise * 2);
    case "unemp": return round1(5.2 + season * 0.15 + noise * 0.2);
    case "ind": return round1(5.4 + season * 0.8 + noise);
    case "retail": return round1(4.6 + season * 0.8 + noise * 1.2);
    case "invest": return round1(3.8 + t * -0.05 + noise);
    case "realestate": return round1(-6.5 + t * 0.35 + noise * 1.5);
    case "fin": return round1(5.6 + season * 1.4 + noise * 1.6);
    case "fx": return round2(3.18 + t * 0.015 + noise * 0.12);
    case "lpr": return round2(3.45 - t * 0.06 + noise * 0.04);
    case "import": return round1(2.8 + season * 1.3 + noise * 2.2);
    case "houseprice": return round1(3.2 + t * 0.05 + season * 0.8 + noise * 0.6);
    case "yield10y": return round2(2.9 - t * 0.08 + season * 0.15 + noise * 0.12);
    case "usdcny": return round2(6.5 + t * 0.05 + season * 0.03 + noise * 0.08);
    case "m1": return round1(4.2 + t * 0.1 + noise * 0.8);
    case "tsfstock": return round1(9.5 - t * 0.02 + noise * 0.3);
    case "loans": return round2(1.8 + Math.abs(noise) * 0.7 + season * 0.5);
    case "gold": return round1(1100 + t * 55 + Math.sin(t * Math.PI * 0.5) * 80 + noise * 30);
    case "carsales": return round1(170 + season * 15 + noise * 12);
    default: return round1(noise);
  }
}

