/** 直接改源文件：把 story 替换进 nodes 数组的对应行 */
function main() {
  const dry = process.argv.includes("--dry");
  const src = readFileSync(FILE, "utf8");
  const lines = src.split("\n");
  let changed = 0;
  const missed: string[] = [];

  for (const [key, story] of Object.entries(EXPAND)) {
    const [id, date] = key.split("|");
    // 定位该场次块
    const idIdx = lines.findIndex((l) => l.includes(`id: "${id}"`));
    if (idIdx < 0) {
      missed.push(`${key}（找不到场次）`);
      continue;
    }
    // 定位该场次内的 nodes 块
    const nodesIdx = lines.findIndex((l, i) => i > idIdx && l.trim().startsWith("nodes: ["));
    if (nodesIdx < 0) {
      missed.push(`${key}（找不到 nodes）`);
      continue;
    }
    // 找到匹配 date 的节点行
    const nodeIdx = lines.findIndex(
      (l, i) => i >= nodesIdx && l.includes(`{ date: "${date}"`)
    );
    if (nodeIdx < 0) {
      missed.push(`${key}（找不到节点）`);
      continue;
    }
    // 该节点行内替换 story: "..."（节点行均为单行对象）
    const line = lines[nodeIdx];
    const m = line.match(/story: "([^"]*)"/);
    if (!m) {
      missed.push(`${key}（该行没有 story 字段）`);
      continue;
    }
    const esc = story.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
    lines[nodeIdx] = line.replace(m[0], `story: "${esc}"`);
    changed++;
  }

  console.log(`改写 ${changed} 个节点 story${dry ? "（dry-run，未落盘）" : ""}`);
  if (missed.length) {
    console.log("未匹配：");
    missed.forEach((m) => console.log(`  - ${m}`));
  }
  if (!dry) writeFileSync(FILE, lines.join("\n"), "utf8");
}

